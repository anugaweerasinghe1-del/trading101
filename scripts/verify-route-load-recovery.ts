import assert from "node:assert/strict";
import { claimRouteReload, isRouteModuleLoadError, ROUTE_RECOVERY_PREFIX } from "../src/lib/routeLoadRecovery";
const error = new TypeError("Failed to fetch dynamically imported module: https://www.thetradehq.com/assets/WhatsNew-CIJOAWUB.js");
const data = new Map<string,string>();
const storage = {getItem: (k:string) => data.get(k) ?? null, setItem: (k:string,v:string) => {data.set(k,v);}};
const page = {pathname:"/whats-new",search:""};
assert.equal(isRouteModuleLoadError(error),true);
assert.equal(isRouteModuleLoadError(new Error("Importing a module script failed.")),true);
assert.equal(isRouteModuleLoadError(new TypeError("error loading dynamically imported module: example")),true);
assert.equal(isRouteModuleLoadError(new Error("Unable to preload CSS for /assets/a.css")),true);
assert.equal(isRouteModuleLoadError(new TypeError("Cannot read properties of undefined")),false);
assert.equal(claimRouteReload(error,page,false,storage),false);
assert.equal(data.size,0);
assert.equal(claimRouteReload(error,page,true,storage),true);
assert.equal(data.get(ROUTE_RECOVERY_PREFIX+"/whats-new"),"1");
assert.equal(claimRouteReload(error,page,true,storage),false);
assert.equal(claimRouteReload(error,{pathname:"/whats-new/",search:""},true,storage),false);
assert.equal(claimRouteReload(error,{pathname:"/wiki/drawdown",search:""},true,storage),true);
for(const pathname of ["/admin","/admin/courses","/contact","/trade","/trade/btc","/portfolio","/auth","/reset-password","/newsletter/confirm","/certificate/verify","/courses/example/lesson","/daily","/practice"]) assert.equal(claimRouteReload(error,{pathname,search:""},true,storage),false,pathname);
assert.equal(claimRouteReload(error,{pathname:"/about",search:"?token=example"},true,storage),false);
assert.equal(claimRouteReload(new Error("ordinary rendering error"),{pathname:"/about",search:""},true,storage),false);
assert.equal(claimRouteReload(error,{pathname:"/about",search:""},true,{getItem:()=>{throw Error("disabled");},setItem:()=>{}}),false);
assert.equal(claimRouteReload(error,{pathname:"/about",search:""},true,{getItem:()=>null,setItem:()=>{}}),false);
assert.equal(data.size,2);
console.log("PASS route module recovery: matching errors, offline/manual fallback, read-only scope, per-tab reload limit, denied storage and sensitive-route protection");
