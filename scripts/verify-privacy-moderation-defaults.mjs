import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const auth = read("src/pages/Auth.tsx");
const review = read("supabase/functions/submit-review/index.ts");
const migration = read("supabase/migrations/20261101030000_private_profiles_and_review_approval.sql");
const privacy = read("src/lib/privacyCopy.ts");
const userReviews = read("src/pages/Reviews.tsx");
const profile = read("src/pages/TraderProfile.tsx");
assert.match(auth, /data: \{ username: parsed\.data\.username, is_public: false \}/);
assert.doesNotMatch(auth, /is_public: true/);
assert.match(auth, /New profiles start private/);
assert.match(profile, /New accounts start private/);
assert.match(migration, /ALTER TABLE public\.profiles ALTER COLUMN is_public SET DEFAULT false/);
assert.match(migration, /ALTER TABLE public\.reviews ALTER COLUMN is_visible SET DEFAULT false/);
assert.match(migration, /pg_get_functiondef\('public\.handle_new_user\(\)'::regprocedure\)/);
assert.doesNotMatch(migration, /UPDATE\s+public\.profiles/i);
assert.doesNotMatch(migration, /UPDATE\s+public\.reviews/i);
assert.match(review, /is_visible: false/);
assert.match(review, /status: "pending_moderation"/);
assert.match(privacy, /New accounts start with a private profile/);
assert.match(userReviews, /awaiting moderation before public display/);
console.log("PASS: new-account and new-review defaults; existing rows preserved");
