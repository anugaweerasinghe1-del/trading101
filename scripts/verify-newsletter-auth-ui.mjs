import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { newsletterAdminError } from "../src/lib/newsletterAdminError.ts";
assert.match(newsletterAdminError(401), /Incorrect TradeHQ admin master key/);
assert.match(newsletterAdminError(429), /Too many unlock attempts/);
assert.match(newsletterAdminError(503), /not configured/);
assert.match(newsletterAdminError(404), /could not be found/);
assert.match(newsletterAdminError(502), /HTTP 502/);
assert.ok(!newsletterAdminError(401).includes("backend unavailable"));
const ui = readFileSync("src/pages/AdminNewsletter.tsx","utf8");
const api = readFileSync("supabase/functions/newsletter-editor/index.ts","utf8");
assert.match(ui, /context\?\.status/);
assert.match(ui, /newsletterAdminError/);
assert.doesNotMatch(ui, /GitHub scheduling secret/);
assert.match(api, /if \(!configuredAdminKey && !scheduled\)/);
assert.match(api, /return reply\(\{ error: "Newsletter administrator configuration is missing\." \}, 503\)/);
assert.match(api, /return reply\(\{ error: "Incorrect TradeHQ admin master key\." \}, 401\)/);
assert.match(api, /equalSecret\(configuredAdminKey, req\.headers\.get\("x-admin-key"\)\)/);
console.log("PASS newsletter admin auth differentiates invalid key, missing config and network errors without weakening access control");
