import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { COURSE_PROGRESS_KEY, parseCourseProgress, loadProgress, markLessonStarted, saveLessonDraft, saveLessonPosition, markLessonCompleted, readLessonDraft } from "../src/lib/courseProgress.ts";
const values = new Map<string,string>();
let events=0;
Object.defineProperty(globalThis,"localStorage",{configurable:true,value:{getItem:(k:string)=>values.get(k)??null,setItem:(k:string,v:string)=>{values.set(k,v);},removeItem:(k:string)=>values.delete(k)}});
Object.defineProperty(globalThis,"window",{configurable:true,value:{dispatchEvent:()=>{events++;}}});
Object.defineProperty(globalThis,"Event",{configurable:true,value:class{constructor(public name:string){}}});
const prior={v:1,tracks:{intro:{lessons:{older:{status:"completed",score:3,completedAt:"2026-10-30T10:00:00Z"}}}},updatedAt:"2026-10-30T10:00:00Z"};
values.set(COURSE_PROGRESS_KEY,JSON.stringify(prior));
markLessonStarted("intro","unfinished");
saveLessonDraft("intro","unfinished",{0:1,1:2});
saveLessonPosition("intro","unfinished",48.5);
let saved=loadProgress();
assert.equal(saved.tracks.intro.lessons.older.status,"completed","old lessons must survive new writes");
assert.equal(saved.tracks.intro.lessons.unfinished.scrolledPct,49);
assert.equal(saved.tracks.intro.lessons.unfinished.quizAnswers?.["1"],2);
assert.equal(readLessonDraft("intro","unfinished").answers["0"],1);
assert.equal(saved.lastLesson?.lesson,"unfinished");
assert.ok(events>=2,"cross-component progress events must be emitted");
saveLessonPosition("intro","unfinished",Infinity);
assert.equal(readLessonDraft("intro","unfinished").scrolledPct,49);
markLessonCompleted("intro","unfinished",2);
saved=loadProgress();
assert.equal(saved.tracks.intro.lessons.unfinished.status,"completed");
assert.equal(saved.tracks.intro.lessons.unfinished.quizAnswers,undefined);
saveLessonDraft("intro","unfinished",{0:9});
saveLessonPosition("intro","unfinished",12);
assert.equal(loadProgress().tracks.intro.lessons.unfinished.status,"completed","reading must never reopen completed lessons");
assert.equal(readLessonDraft("intro","unfinished").scrolledPct,100);
const polluted=parseCourseProgress(JSON.stringify({v:1,tracks:{intro:{lessons:{draft:{status:"in-progress",quizAnswers:{"0":2,"3":999,"oops":4},scrolledPct:12}}}},updatedAt:"bad"}));
assert.deepEqual({...polluted.tracks.intro.lessons.draft.quizAnswers},{"0":2});
assert.equal(polluted.tracks.intro.lessons.draft.scrolledPct,12);
const lesson=readFileSync("src/pages/CourseLesson.tsx","utf8");
assert.match(lesson,/saveLessonDraft\(track.slug, lesson.slug, updated\)/);
assert.match(lesson,/saveLessonPosition\(track.slug, lesson.slug/);
assert.match(lesson,/Resume reading near/);
console.log("PASS legacy migration, partial quizzes, reading position, completion safety and resumable browser learning");
